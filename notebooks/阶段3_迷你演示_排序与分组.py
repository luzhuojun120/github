"""
阶段3 · 迷你演示：排序 + 分组平均（一眼看懂）
============================================
就 6 行假数据，专门用来"看见" sort_values 和 groupby 怎么工作。
跑完对照输出想一遍，比看十遍文字管用。
"""

import pandas as pd

# 一张 6 行的迷你表：2 列特征 + 1 列活动编号
df = pd.DataFrame({
    "活动编号": [3, 1, 2, 1, 3, 2],
    "特征X":    [0.5, 0.9, 0.2, 0.3, 0.8, 0.6],
    "特征Y":    [10, 20, 30, 40, 50, 60],
})
print("===== 排序前（行的顺序是乱的）=====")
print(df)

# ---- 排序：先按活动编号，再在组内按特征X ----
df2 = df.sort_values(["活动编号", "特征X"])
print("\n===== sort_values([\"活动编号\", \"特征X\"]) 之后 =====")
print("看活动编号：1 全在最上，2 居中，3 垫底（第1步）")
print("再看同编号内部：特征X 小的在前（第2步，只在组内排）")
print(df2)

# ---- 分组求平均：看 3 个组怎么各算各的 ----
print("\n===== groupby(\"活动编号\")[\"特征X\"].mean() =====")
print("3 个组 → 3 行。每行的数字 = 那一组内部算出的平均：")
print(df.groupby("活动编号")["特征X"].mean())

# ---- 如果同时要 2 个特征列的平均：2 列 × 3 组 = 6 个数 ----
print("\n===== groupby(\"活动编号\")[[\"特征X\", \"特征Y\"]].mean() =====")
print("3 组 × 2 列 = 6 个平均值，形状是 3 行 × 2 列：")
print(df.groupby("活动编号")[["特征X", "特征Y"]].mean())

# ---- 想一想：如果是 UCI HAR（6 活动 × 3 特征）----
print("\n===== 回到 UCI HAR：6 个活动 × 3 个特征 =====")
print("形状会是 6 行 × 3 列 = 18 个平均值 —— 这就是你看到的'这么多'")
print("规律：行数 = 组的数量，列数 = 你选的列数")
