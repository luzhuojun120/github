import os
import pandas as pd

# 让相对路径从本文件位置算起
os.chdir(os.path.dirname(__file__))
DATA_DIR = os.path.join("..", "data", "UCI HAR Dataset")

# ============================================================
# 第 1 步：读特征名（142 集 数据读取）
# features.txt 里每行是 "1 tBodyAcc-mean()-X"，用空格分开
# ============================================================
features = pd.read_csv(
    os.path.join(DATA_DIR, "features.txt"),
    sep=r"\s+",          # 按空格（可能多个）分开
    header=None,          # 文件里没有表头行
    names=["序号", "特征名"],  # 我们自己起两列名字
)
print("=== 特征表前 3 行 ===")
print(features.head(3))
print(f"特征总数: {len(features)}")   # 应该是 561

# UCI HAR 的特征名里有一小部分重复（真实数据常见）。
# pandas 不允许重复列名，所以给重复的名字加后缀 _2 / _3 去重：
seen = {}          # 记录每个名字出现过几次
clean_names = []   # 存去重后的名字
for name in features["特征名"]:
    if name in seen:                 # 之前见过 → 重复了
        seen[name] += 1
        clean_names.append(f"{name}_{seen[name]}")
    else:                            # 第一次见
        seen[name] = 1
        clean_names.append(name)
print(f"去重前名字数: {len(features)}, 去重后列名数: {len(clean_names)}")

# ============================================================
# 第 2 步：读训练数据 X_train.txt（7352 行 × 561 列）
# 用特征名当列名，这样每列知道是什么特征
# ============================================================
X_train = pd.read_csv(
    os.path.join(DATA_DIR, "train", "X_train.txt"),
    sep=r"\s+",
    header=None,
    names=clean_names,   # 用去重后的特征名
)
print("\n=== 训练数据形状（行, 列）===")
print(X_train.shape)          # 应该是 (7352, 561)

# ============================================================
# 第 3 步：读标签 y_train.txt（每行一个数字 1-6）
# ============================================================
y_train = pd.read_csv(
    os.path.join(DATA_DIR, "train", "y_train.txt"),
    header=None,
    names=["活动编号"],
)
print("\n=== 标签前 5 行 ===")
print(y_train.head())
print(f"标签数量: {len(y_train)}")   # 应该也是 7352

# ============================================================
# 第 4 步：把标签和特征并成一张大表（140 集 DataFrame 合并思路）
# 这样一张表 = 一个完整数据集，每行一个样本
# ============================================================
df = X_train.copy()            # 先复制特征表
df["活动编号"] = y_train["活动编号"]   # 加一列标签
print("\n=== 合并后的表 ===")
print(df.shape)               # (7352, 562)  多了标签一列

# ============================================================
# 第 5 步：数据查询（143 集）
# 想快速了解一张表：shape / info / describe
# ============================================================
print("\n=== info(): 每列类型、有没有缺失 ===")
# df.info()  # 561 列太多，先注释，想看可以打开

print("\n=== describe(): 数值列的统计（均值/标准差/最大最小）===")
print(df.describe().iloc[:, :3])   # 只看前 3 列的特征，避免刷屏

# ============================================================
# 第 6 步：数据过滤（144 集 · 你正在学的重点）
# 目标：把"某个活动"的样本单独挑出来
# ============================================================
# 6.1 先看每种活动有几个样本
print("\n=== 每种活动的样本数（value_counts）===")
print(df["活动编号"].value_counts())   # 6 种活动加起来 = 7352

# 6.2 只留下"活动 6（LAYING 躺着）"的样本
# 注意：df["活动编号"] 是列，== 6 得到一个 True/False 的 Series
# 把它放进 df[ ] 里，就能过滤出 True 的那些行
lying = df[df["活动编号"] == 6]
print("\n=== 过滤出躺着(6)的样本 ===")
print(f"数量: {len(lying)}")        # 应该 1407

# 6.3 组合过滤：躺着 + 某个特征值很大（两个条件用 & 连接）
# 比如第一个特征（tBodyAcc-mean()-X 第一列）> 0.3 的躺着样本
first_feat = clean_names[0]   # 第一个特征名（去重后的）
lying_active = df[(df["活动编号"] == 6) & (df[first_feat] > 0.3)]
print(f"\n躺着且第一个特征>0.3 的样本数: {len(lying_active)}")

# ============================================================
# 检验：全程没报错 + 出现数字 (7352, 561) (7352, 562) 1407
# ============================================================
print("\n✅ 模块1 跑通！你已经用 Pandas 读懂了 UCI HAR 的表格结构。")
print("   下一步（等你学完 145 数据清洗 / 146 排序 / 147 分组，解锁模块2）")
dups = {k: v for k, v in seen.items() if v > 1}
print(f"重复的特征名有 {len(dups)} 个，例如:", list(dups.items())[:5])

